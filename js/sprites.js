// HELPER: Draw a sprite to canvas
// ========================================

function drawSprite(ctx, sprite, x, y, pixelSize = 1) {
    for (let row = 0; row < sprite.length; row++) {
        for (let col = 0; col < sprite[row].length; col++) {
            const colorKey = sprite[row][col];
            if (colorKey === 0) continue;
            const color = PALETTE[colorKey];
            if (!color) continue;
            ctx.fillStyle = color;
            ctx.fillRect(
                Math.floor(x + col * pixelSize),
                Math.floor(y + row * pixelSize),
                pixelSize,
                pixelSize
            );
        }
    }
}

// Draw a sprite flipped horizontally
function drawSpriteFlipped(ctx, sprite, x, y, pixelSize = 1) {
    ctx.save();
    ctx.translate(x + sprite[0].length * pixelSize, y);
    ctx.scale(-1, 1);
    drawSprite(ctx, sprite, 0, 0, pixelSize);
    ctx.restore();
}

